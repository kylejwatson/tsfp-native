"""
re/names.json: what we know about the game, in one place.

    py -3 re/names.py header    regenerate src/tsfp_names.h (addresses and
                                struct offsets for the C overrides)
    py -3 re/names.py ghidra    apply every name, signature, type and comment
                                to the Ghidra project (ghidra/tsfp.gpr) through
                                ghidra-cli and re/ghidra/ApplyNames.java
    py -3 re/names.py pull      add names given in the Ghidra GUI (user-defined
                                functions and labels not in the file yet)
    py -3 re/names.py check     duplicates, bad addresses, sort order

The JSON is the source of truth: name things there (or in Ghidra, then pull),
never only in a comment. Each entry carries a "source" saying how it is known.
"""

import json
import os
import re
import subprocess
import sys
from datetime import date

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
NAMES = os.path.join(HERE, "names.json")
HEADER = os.path.join(ROOT, "src", "tsfp_names.h")
GHIDRA_CLI = os.environ.get("GHIDRA_CLI", r"C:\ghidra-cli\ghidra.exe")
# Forward slashes: ghidra-cli matches a running bridge by the path string.
PROJECT = os.path.join(ROOT, "ghidra", "tsfp.gpr").replace("\\", "/")
PROGRAM = "default.xbe"


def load():
    with open(NAMES, encoding="utf-8") as f:
        return json.load(f)


def save(doc):
    for key in ("functions", "globals"):
        doc[key].sort(key=lambda e: int(e["addr"], 16))
    with open(NAMES, "w", encoding="utf-8", newline="\n") as f:
        json.dump(doc, f, indent=1)
        f.write("\n")


def ident(name):
    return re.sub(r"[^0-9A-Za-z]+", "_", name).strip("_").upper()


def cmd_header(doc):
    out = [
        "/* Generated by re/names.py from re/names.json -- do not edit; edit the",
        " * JSON and run `py -3 re/names.py header`. Guest addresses and struct",
        " * offsets of TimeSplitters: Future Perfect (PAL default.xbe). */",
        "#ifndef TSFP_NAMES_H",
        "#define TSFP_NAMES_H",
        "",
        "/* Functions */",
    ]
    seen = set()

    def emit(macro, value, comment=None):
        if macro in seen:
            return
        seen.add(macro)
        line = "#define %-40s %s" % (macro, value)
        if comment:
            line += "  /* %s */" % comment.replace("*/", "* /")
        out.append(line)

    for e in doc["functions"]:
        emit("TSFP_FN_" + ident(e["name"]), e["addr"] + "u")
    out += ["", "/* Globals */"]
    for e in doc["globals"]:
        emit("TSFP_" + ident(e["name"]), e["addr"] + "u", e.get("type"))
    for s in doc.get("structs", []):
        out += ["", "/* struct %s%s */" % (s["name"], ", size " + s["size"] if s.get("size") else "")]
        if s.get("size"):
            emit("TSFP_%s_SIZE" % ident(s["name"]), s["size"] + "u")
        for f in s["fields"]:
            emit("TSFP_%s_%s" % (ident(s["name"]), ident(f["name"])), f["off"] + "u", f.get("type"))
    if doc.get("actions"):
        out += ["", "/* Control actions (Player.control_axis index) */"]
        for k, v in doc["actions"].items():
            emit("TSFP_ACTION_" + ident(v), k + "u")
    out += ["", "#endif", ""]
    with open(HEADER, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out))
    print("wrote", os.path.relpath(HEADER, ROOT), "(%d names)" % len(seen))


def cli(*args, script_args=()):
    tail = ["--", *script_args] if script_args else []
    return subprocess.run([GHIDRA_CLI, *args, "--project", PROJECT, "--program", PROGRAM, *tail],
                          capture_output=True, text=True)


def cmd_ghidra(doc):
    script = os.path.join(HERE, "ghidra", "ApplyNames.java")
    r = cli("script", "run", script, script_args=(NAMES,))
    sys.stdout.write(r.stdout)
    sys.stderr.write(r.stderr)
    if r.returncode:
        print("ghidra-cli failed; is the bridge running?  %s start --project %s --program %s"
              % (GHIDRA_CLI, PROJECT, PROGRAM), file=sys.stderr)
    return r.returncode


def cmd_pull(doc):
    r = cli("symbol", "list", "--limit", "0", "--json")
    if r.returncode:
        sys.stderr.write(r.stderr)
        return 1
    syms = json.loads(r.stdout)
    have = {int(e["addr"], 16) for e in doc["functions"] + doc["globals"]}
    src = "Ghidra GUI (pulled %s)" % date.today().isoformat()
    added = 0
    for s in syms:
        if s.get("source") != "USER_DEFINED":
            continue
        a = int(s["address"], 16)
        if a in have:
            continue
        key = "functions" if s["type"] == "Function" else "globals"
        doc[key].append({"addr": "0x%08X" % a, "name": s["name"], "source": src})
        have.add(a)
        added += 1
    save(doc)
    print("pulled", added, "new name(s)")
    return 0


def cmd_check(doc):
    bad = 0
    for key in ("functions", "globals"):
        addrs = [int(e["addr"], 16) for e in doc[key]]
        if addrs != sorted(addrs):
            print(key, "are not sorted by address (pull or save fixes it)")
            bad += 1
        names = {}
        for e in doc[key]:
            if e["name"] in names:
                print("%s: %s at both %s and %s" % (key, e["name"], names[e["name"]], e["addr"]))
                bad += 1
            names[e["name"]] = e["addr"]
            if "source" not in e:
                print("%s %s has no source" % (e["addr"], e["name"]))
                bad += 1
    for s in doc.get("structs", []):
        offs = [int(f["off"], 16) for f in s["fields"]]
        if offs != sorted(offs) or len(set(offs)) != len(offs):
            print("struct", s["name"], "fields out of order or repeated")
            bad += 1
    print("ok" if not bad else "%d problem(s)" % bad)
    return 1 if bad else 0


def main():
    cmd = sys.argv[1] if len(sys.argv) > 1 else ""
    doc = load()
    if cmd == "header":
        return cmd_header(doc)
    if cmd == "ghidra":
        return cmd_ghidra(doc)
    if cmd == "pull":
        return cmd_pull(doc)
    if cmd == "check":
        return cmd_check(doc)
    print(__doc__)
    return 2


if __name__ == "__main__":
    sys.exit(main() or 0)
